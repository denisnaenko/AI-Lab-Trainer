"""Уровни сложности.

Уровень задаётся объективными параметрами задания, а не меткой от LLM:
исследования показывают, что метки сложности, которые ставит модель, почти
не связаны с реальной сложностью (An & Wang, 2026), а упрощать задания модели
умеют плохо (Bloom-aligned framework, 2026). Поэтому каждый уровень описан
набором проверяемых признаков, и генерация идёт от базового уровня к сложному.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Level:
    number: int
    name: str
    summary: str
    traits: tuple[str, ...]
    starter_style: str
    min_auto_requirements: int
    max_auto_requirements: int


LEVELS: dict[int, Level] = {
    1: Level(
        number=1,
        name="Базовый",
        summary="Один сценарий работы агента без обработки ошибок; подробный шаблон с подсказками.",
        traits=(
            "один основной сценарий (один инструмент, один вызов LLM или один цикл)",
            "входные данные и ответы LLM всегда корректны",
            "в шаблоне есть сигнатуры, docstring и подсказки TODO для каждого шага",
        ),
        starter_style="подробный: сигнатуры, docstring, пошаговые TODO-подсказки",
        min_auto_requirements=3,
        max_auto_requirements=4,
    ),
    2: Level(
        number=2,
        name="Средний",
        summary="Несколько шагов или инструментов, ограничения и обработка ожидаемых ошибок.",
        traits=(
            "несколько шагов, инструментов или маршрутов",
            "ограничения (число шагов, размер окна, пороги)",
            "обработка ожидаемых ошибок: неизвестный инструмент, неполные данные",
            "в шаблоне только сигнатуры и краткие подсказки",
        ),
        starter_style="сигнатуры и краткие подсказки",
        min_auto_requirements=5,
        max_auto_requirements=6,
    ),
    3: Level(
        number=3,
        name="Продвинутый",
        summary="Устойчивость к сбоям LLM и инструментов, повторы, трассировка, композиция агентов.",
        traits=(
            "обработка исключений и некорректных ответов LLM",
            "повторные попытки с обратной связью модели",
            "трассировка или журналирование шагов агента",
            "композиция нескольких агентов или вызовов LLM",
            "минимальный шаблон: студент сам проектирует внутреннюю структуру",
        ),
        starter_style="минимальный: только публичный интерфейс",
        min_auto_requirements=7,
        max_auto_requirements=8,
    ),
}


def get_level(number: int) -> Level:
    if number not in LEVELS:
        raise ValueError(f"Уровень сложности должен быть 1, 2 или 3, получено: {number}")
    return LEVELS[number]
